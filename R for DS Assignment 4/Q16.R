# [ ] (Single Brackets):
# Used to extract elements from a vector, list, or data frame.
# Returns a list or data frame when used with a list or data frame respectively.
# Keeps the structure of the data. If you extract a subset from a list using single brackets, you get a sublist.
# Can be used to extract multiple elements at a time.
my_list[2]

# [[ ]] (Double Brackets):
# Used to extract elements from a list.
# Returns the element itself (not a list) when used with a list.
# Used to access individual components of a list directly.
# Can only be used to extract a single element at a time.
my_list[[2]]




